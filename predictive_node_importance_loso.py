if HAS_TORCH:

    class EEGSequenceCNN(nn.Module):
        def __init__(self, n_features=TOTAL_FEATURES):
            super().__init__()
            self.net = nn.Sequential(
                nn.Conv1d(n_features, 64, kernel_size=2, padding=1),
                nn.BatchNorm1d(64),
                nn.ReLU(),
                nn.Dropout(0.30),

                nn.Conv1d(64, 32, kernel_size=2, padding=1),
                nn.BatchNorm1d(32),
                nn.ReLU(),

                nn.AdaptiveAvgPool1d(1),
                nn.Flatten(),
                nn.Linear(32, 16),
                nn.ReLU(),
                nn.Dropout(0.40),
                nn.Linear(16, 1),
            )

        def forward(self, x):
            return self.net(x)


def fit_cnn_model(X_train, y_train, seed=RANDOM_SEED, epochs=18):
    """Train the CNN once on outer-training subjects only."""

    if not HAS_TORCH:
        raise RuntimeError(
            "PyTorch is not installed. Install it with: pip install torch"
        )

    torch.manual_seed(int(seed))
    np.random.seed(int(seed))

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = EEGSequenceCNN(X_train.shape[-1]).to(device)

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=1e-3,
        weight_decay=1e-4,
    )
    loss_fn = nn.BCEWithLogitsLoss()

    x_train = torch.tensor(
        X_train.transpose(0, 2, 1),
        dtype=torch.float32,
        device=device,
    )
    y_train_tensor = torch.tensor(
        y_train.reshape(-1, 1),
        dtype=torch.float32,
        device=device,
    )

    batch_size = min(128, len(x_train))
    generator = torch.Generator(device="cpu")
    generator.manual_seed(int(seed))

    model.train()
    for _ in range(epochs):
        permutation = torch.randperm(
            len(x_train),
            generator=generator,
        )

        for start in range(0, len(x_train), batch_size):
            batch_indices = permutation[start:start + batch_size].to(device)

            optimizer.zero_grad()
            logits = model(x_train[batch_indices])
            loss = loss_fn(logits, y_train_tensor[batch_indices])
            loss.backward()
            optimizer.step()

    model.eval()
    return model, device


def predict_cnn(model, device, X):
    x = torch.tensor(
        X.transpose(0, 2, 1),
        dtype=torch.float32,
        device=device,
    )

    model.eval()
    with torch.no_grad():
        logits = model(x).squeeze(1)
        probabilities = torch.sigmoid(logits).cpu().numpy()

    return (probabilities >= 0.5).astype(int)


