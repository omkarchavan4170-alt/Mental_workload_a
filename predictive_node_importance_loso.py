def create_plots(outdir, baseline_summary, summary, prior_ranking_path=None):
    """Create comparison and importance plots."""

    # Plot 1: classifier baseline comparison.
    order = baseline_summary.sort_values(
        "mean_balanced_accuracy",
        ascending=False,
    )

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.bar(
        order["model"],
        order["mean_balanced_accuracy"],
        yerr=order["sd_balanced_accuracy"],
        capsize=4,
    )
    ax.set_ylim(0, 1)
    ax.set_ylabel("Balanced accuracy")
    ax.set_title("LOSO baseline performance by classifier")
    ax.grid(axis="y", alpha=0.25)
    plt.xticks(rotation=20, ha="right")
    fig.tight_layout()
    fig.savefig(
        outdir / "01_model_baseline_comparison.png",
        dpi=220,
    )
    plt.close(fig)

    models_order = list(order["model"])

    # Plot 2: classifier x electrode heatmap.
    heat = summary.pivot(
        index="model",
        columns="channel",
        values="mean_importance_drop",
    ).reindex(index=models_order, columns=CHANNELS)

    fig, ax = plt.subplots(figsize=(14, 5))
    im = ax.imshow(heat.values, aspect="auto", cmap="viridis")
    ax.set_xticks(range(len(CHANNELS)))
    ax.set_xticklabels(CHANNELS)
    ax.set_yticks(range(len(models_order)))
    ax.set_yticklabels(models_order)
    ax.set_title(
        "Predictive electrode importance: LOSO balanced-accuracy drop"
    )
    ax.set_xlabel("EEG electrode")
    ax.set_ylabel("Classifier")
    fig.colorbar(im, ax=ax, label="Mean balanced-accuracy drop")
    fig.tight_layout()
    fig.savefig(
        outdir / "02_model_node_importance_heatmap.png",
        dpi=220,
    )
    plt.close(fig)

    # Plot 3: grouped comparison across classifiers.
    pivot = summary.pivot(
        index="channel",
        columns="model",
        values="mean_importance_drop",
    ).reindex(CHANNELS)

    ax = pivot.plot(
        kind="bar",
        figsize=(15, 6),
        width=0.82,
    )
    ax.set_ylabel("Mean balanced-accuracy drop")
    ax.set_xlabel("EEG electrode")
    ax.set_title("Predictive importance comparison across classifiers")
    ax.axhline(0, linewidth=0.8)
    ax.grid(axis="y", alpha=0.25)
    plt.xticks(rotation=0)
    plt.tight_layout()
    plt.savefig(
        outdir / "03_grouped_node_importance_by_model.png",
        dpi=220,
    )
    plt.close()

    # Plot 4: one ranking plot per model.
    fig, axes = plt.subplots(
        len(models_order),
        1,
        figsize=(11, 4 * len(models_order)),
    )
    if len(models_order) == 1:
        axes = [axes]

    for ax, model_name in zip(axes, models_order):
        sub = summary[
            summary["model"] == model_name
        ].sort_values(
            "mean_importance_drop",
            ascending=True,
        )

        ax.barh(
            sub["channel"],
            sub["mean_importance_drop"],
        )
        ax.axvline(0, linewidth=0.8)
        ax.set_title(model_name)
        ax.set_xlabel(
            "Balanced-accuracy drop after electrode-group permutation"
        )
        ax.grid(axis="x", alpha=0.25)

    fig.suptitle(
        "Predictive electrode importance rankings by classifier",
        y=1.0,
    )
    fig.tight_layout()
    fig.savefig(
        outdir / "04_node_rankings_each_model.png",
        dpi=220,
        bbox_inches="tight",
    )
    plt.close(fig)

    # Plot 5: fraction of subjects with positive importance.
    consistency = summary.pivot(
        index="channel",
        columns="model",
        values="fraction_subjects_positive",
    ).reindex(CHANNELS)

    fig, ax = plt.subplots(figsize=(14, 5))
    im = ax.imshow(
        consistency.T.values,
        aspect="auto",
        cmap="Blues",
        vmin=0,
        vmax=1,
    )
    ax.set_xticks(range(len(CHANNELS)))
    ax.set_xticklabels(CHANNELS)
    ax.set_yticks(range(len(consistency.columns)))
    ax.set_yticklabels(consistency.columns)
    ax.set_title(
        "Consistency: fraction of held-out subjects with positive importance"
    )
    ax.set_xlabel("EEG electrode")
    ax.set_ylabel("Classifier")
    fig.colorbar(im, ax=ax, label="Fraction of subjects")
    fig.tight_layout()
    fig.savefig(
        outdir / "05_subject_consistency_heatmap.png",
        dpi=220,
    )
    plt.close(fig)

    # Plot 6: compare with previous network-effect ranking, if supplied.
    if prior_ranking_path is not None:
        prior_ranking_path = Path(prior_ranking_path)

    if prior_ranking_path is not None and prior_ranking_path.exists():
        prior = pd.read_csv(prior_ranking_path)

        required = {"channel", "rank"}
        if required.issubset(prior.columns):
            prior = prior[["channel", "rank"]].rename(
                columns={"rank": "network_effect_rank"}
            )

            predictive = (
                summary.groupby("channel")["mean_importance_drop"]
                .mean()
                .sort_values(ascending=False)
                .rank(method="min", ascending=False)
                .rename("predictive_importance_rank")
                .reset_index()
            )

            compare = prior.merge(
                predictive,
                on="channel",
                how="inner",
            )
            compare.to_csv(
                outdir / "network_vs_predictive_node_rankings.csv",
                index=False,
            )

            fig, ax = plt.subplots(figsize=(8, 7))
            ax.scatter(
                compare["network_effect_rank"],
                compare["predictive_importance_rank"],
                s=90,
            )

            for _, row in compare.iterrows():
                ax.annotate(
                    row["channel"],
                    (
                        row["network_effect_rank"],
                        row["predictive_importance_rank"],
                    ),
                    xytext=(4, 4),
                    textcoords="offset points",
                )

            ax.set_xlabel("Network-effect rank")
            ax.set_ylabel("Predictive-importance rank")
            ax.set_title(
                "Network importance vs predictive electrode importance"
            )
            ax.invert_xaxis()
            ax.invert_yaxis()
            ax.grid(alpha=0.25)
            fig.tight_layout()
            fig.savefig(
                outdir / "06_network_vs_predictive_ranking.png",
                dpi=220,
            )
            plt.close(fig)


