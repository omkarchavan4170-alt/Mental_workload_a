CHANNELS = [
    "AF3", "F7", "F3", "FC5", "T7", "P7", "O1",
    "O2", "P8", "T8", "FC6", "F4", "F8", "AF4",
]

N_BANDS = 5
FEATURES_PER_BAND = 120
COHERENCE_FEATURES_PER_BAND = 91
GRAPH_FEATURES_PER_BAND = 29
TOTAL_FEATURES = N_BANDS * FEATURES_PER_BAND  # 600

SEQ_LEN = 4                 # 4 x 5-second windows = 20 seconds
WINDOW_SECONDS = 5
RANDOM_SEED = 42


# ---------------------------------------------------------------------
# FEATURE GROUP RECONSTRUCTION
# ---------------------------------------------------------------------

def build_feature_groups(feature_columns):
    """
    Reconstruct electrode-specific groups using the exact order in the
    supplied feature_extraction.py.

    For each band, the concatenation is:
      0..90   : 91 coherence values from np.triu_indices(14, k=1)
      91      : global average shortest path
      92..119 : for each channel, closeness then clustering

    Per electrode across five bands:
      13 incident edges x 5 bands = 65 coherence features
      5 closeness features
      5 clustering features
      Total = 75 feature indices

    The global average-shortest-path features are not assigned to a node.
    """

    if len(feature_columns) != TOTAL_FEATURES:
        raise ValueError(
            f"Expected {TOTAL_FEATURES} feature columns after removing "
            f"the CSV index, found {len(feature_columns)}."
        )

    actual = [str(c).strip() for c in feature_columns]
    expected = [str(i) for i in range(TOTAL_FEATURES)]

    if actual != expected:
        raise ValueError(
            "Feature columns are not the expected numeric sequence 0..599. "
            "Do not guess the feature ordering. Check the feature extractor "
            "and CSV export."
        )

    groups = {channel: set() for channel in CHANNELS}

    # This reproduces np.triu_indices(14, k=1), used by the feature extractor.
    edge_i, edge_j = np.triu_indices(len(CHANNELS), k=1)

    for band_idx in range(N_BANDS):
        band_start = band_idx * FEATURES_PER_BAND

        # 1) Coherence edges: one feature is assigned to both endpoints.
        for edge_idx, (i, j) in enumerate(zip(edge_i, edge_j)):
            feature_idx = band_start + edge_idx
            groups[CHANNELS[i]].add(feature_idx)
            groups[CHANNELS[j]].add(feature_idx)

        # 2) Graph features start after the 91 coherence features.
        graph_start = band_start + COHERENCE_FEATURES_PER_BAND

        # graph_start is the global average-shortest-path feature.
        # It is intentionally not attributed to any single electrode.

        # The source extractor appends closeness then clustering for each node.
        for node_idx, channel in enumerate(CHANNELS):
            closeness_idx = graph_start + 1 + (2 * node_idx)
            clustering_idx = graph_start + 2 + (2 * node_idx)

            groups[channel].add(closeness_idx)
            groups[channel].add(clustering_idx)

    groups = {
        channel: sorted(indices)
        for channel, indices in groups.items()
    }

    print("\nElectrode feature-group validation:")
    for channel in CHANNELS:
        count = len(groups[channel])
        print(f"  {channel}: {count} features")
        if count != 75:
            raise ValueError(
                f"Expected 75 grouped features for {channel}, found {count}."
            )

    # Check global graph path features are not included in node groups.
    global_path_indices = {
        band_idx * FEATURES_PER_BAND + COHERENCE_FEATURES_PER_BAND
        for band_idx in range(N_BANDS)
    }
    all_grouped = set().union(*[set(v) for v in groups.values()])
    if global_path_indices.intersection(all_grouped):
        raise RuntimeError(
            "A global average-shortest-path feature was incorrectly assigned "
            "to an electrode."
        )

    return groups


