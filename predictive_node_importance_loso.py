def load_recordings(feature_dir):
    """
    Load each recording separately and create sequences only within that
    recording. This prevents sequences crossing recording boundaries.

    Expected files:
      COH_sub01_hi.csv
      COH_sub01_lo.csv
      ...
      COH_sub48_hi.csv
      COH_sub48_lo.csv

    Expected CSV layout:
      Unnamed: 0, 0, 1, ..., 599
      30 rows
    """

    feature_dir = Path(feature_dir)

    if not feature_dir.exists():
        raise FileNotFoundError(f"Feature directory does not exist: {feature_dir}")

    files = sorted(feature_dir.glob("COH_sub*_*.csv"))

    if not files:
        raise FileNotFoundError(
            f"No COH_sub*_*.csv files found in {feature_dir}"
        )

    rows = []
    feature_columns = None
    loaded_recordings = 0
    seen_recordings = set()

    for path in files:
        match = re.fullmatch(r"COH_sub(\d+)_(hi|lo)", path.stem)
        if not match:
            continue

        subject = int(match.group(1))
        condition = match.group(2)
        recording_key = (subject, condition)

        if recording_key in seen_recordings:
            raise ValueError(f"Duplicate recording detected: {path.name}")
        seen_recordings.add(recording_key)

        df = pd.read_csv(path)

        # The source CSV was saved with pandas' default index=True.
        # Remove only the exported index column, not a real feature.
        unnamed_columns = [
            col for col in df.columns
            if str(col).strip().lower().startswith("unnamed:")
        ]
        if unnamed_columns:
            df = df.drop(columns=unnamed_columns)

        # Also support an explicitly named window index if present.
        if "window_index" in df.columns:
            df = df.drop(columns=["window_index"])

        if df.shape != (30, TOTAL_FEATURES):
            raise ValueError(
                f"{path.name} has shape {df.shape}; expected "
                f"(30, {TOTAL_FEATURES}) after removing exported index columns. "
                f"Columns start: {list(df.columns[:5])}"
            )

        current_columns = list(df.columns)
        if feature_columns is None:
            feature_columns = current_columns
        elif current_columns != feature_columns:
            raise ValueError(
                f"Feature column names/order differ in {path.name}. "
                "All recordings must have identical feature ordering."
            )

        try:
            values = df.to_numpy(dtype=np.float32)
        except Exception as exc:
            raise ValueError(
                f"Non-numeric feature data found in {path.name}: {exc}"
            ) from exc

        if not np.isfinite(values).all():
            raise ValueError(f"NaN or Inf values found in {path.name}")

        label = 1 if condition == "hi" else 0

        # 30 windows, sequence length 4, stride 1 => 27 sequences/recording.
        for start in range(len(values) - SEQ_LEN + 1):
            sequence = values[start:start + SEQ_LEN]
            rows.append((subject, condition, label, start, sequence))

        loaded_recordings += 1

    if not rows:
        raise RuntimeError(
            f"No valid recordings loaded from {feature_dir}. "
            "Check filenames and expected COH_subNN_hi/lo naming."
        )

    # Check every detected subject has both low and high recordings.
    subjects_found = sorted({subject for subject, _ in seen_recordings})
    for subject in subjects_found:
        conditions = {
            condition
            for subj, condition in seen_recordings
            if subj == subject
        }
        if conditions != {"hi", "lo"}:
            raise ValueError(
                f"Subject {subject} does not have both hi and lo recordings. "
                f"Found: {sorted(conditions)}"
            )

    X = np.stack([row[4] for row in rows]).astype(np.float32)
    subject_ids = np.array([row[0] for row in rows], dtype=int)
    conditions = np.array([row[1] for row in rows])
    y = np.array([row[2] for row in rows], dtype=int)
    starts = np.array([row[3] for row in rows], dtype=int)

    print(f"Loaded CSV recordings: {loaded_recordings}")
    print(f"Unique subjects: {len(subjects_found)}")
    print(f"Sequence tensor shape: {X.shape}")

    return (
        X,
        y,
        subject_ids,
        conditions,
        starts,
        feature_columns,
        loaded_recordings,
    )


