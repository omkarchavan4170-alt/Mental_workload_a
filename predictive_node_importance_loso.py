"""
Predictive EEG Electrode Importance for the STEW Dataset
========================================================

This script performs:
1. Loading 96 STEW feature recordings (48 subjects x low/high workload).
2. Reconstructing the exact 600-feature column order produced by the
   user's feature_extraction.py.
3. Creating 4-window (20-second) sequences within each recording.
4. Outer Leave-One-Subject-Out (LOSO) evaluation.
5. Grouped permutation importance for each of the 14 EEG electrodes.
6. Subject-level summaries, bootstrap confidence intervals and FDR correction.
7. Comparison plots across classifiers.

IMPORTANT:
- This is an exploratory LOSO implementation with fixed hyperparameters.
- For a publication-grade final study, add nested subject-wise tuning,
  validation-based early stopping, and channel-subset retraining.
- The electrode groups overlap because each coherence edge belongs to
  both electrodes connected by that edge. Importance values are not additive.
- The script assumes the feature CSVs were generated by the exact
  feature_extraction.py code supplied by the user:
      5 bands x [91 coherence + 1 average path + 14*(closeness, clustering)]
      = 600 features.
- The CSV's first "Unnamed: 0" column is only a pandas-exported row index
  and is removed. The remaining columns must be 0..599 in order.
"""

