def metric_pack(y_true, y_pred):
    return {
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "accuracy": accuracy_score(y_true, y_pred),
        "macro_f1": f1_score(
            y_true,
            y_pred,
            average="macro",
            zero_division=0,
        ),
    }


def fdr_bh(p_values):
    """Benjamini-Hochberg false-discovery-rate adjustment."""

    p = np.asarray(p_values, dtype=float)
    adjusted = np.full(p.shape, np.nan)

    valid_indices = np.where(np.isfinite(p))[0]
    if len(valid_indices) == 0:
        return adjusted

    valid_p = p[valid_indices]
    order = np.argsort(valid_p)
    ranked_p = valid_p[order]

    ranked_adjusted = (
        ranked_p * len(ranked_p) / np.arange(1, len(ranked_p) + 1)
    )
    ranked_adjusted = np.minimum.accumulate(ranked_adjusted[::-1])[::-1]
    ranked_adjusted = np.clip(ranked_adjusted, 0, 1)

    restored = np.empty_like(ranked_adjusted)
    restored[order] = ranked_adjusted
    adjusted[valid_indices] = restored

    return adjusted


def paired_wilcoxon_greater_than_zero(values):
    """One-sided paired Wilcoxon signed-rank test against zero."""

    x = np.asarray(values, dtype=float)
    x = x[np.isfinite(x)]

    if len(x) < 2 or np.allclose(x, 0):
        return np.nan

    try:
        return float(wilcoxon(x, alternative="greater").pvalue)
    except ValueError:
        return np.nan


def bootstrap_ci(values, seed=RANDOM_SEED, n_boot=2000):
    """Bootstrap mean CI by resampling subjects, not sequences."""

    x = np.asarray(values, dtype=float)
    x = x[np.isfinite(x)]

    if len(x) == 0:
        return np.nan, np.nan

    rng = np.random.default_rng(seed)
    boot_means = np.empty(n_boot)

    for index in range(n_boot):
        sample = rng.choice(x, size=len(x), replace=True)
        boot_means[index] = sample.mean()

    return tuple(np.quantile(boot_means, [0.025, 0.975]))


